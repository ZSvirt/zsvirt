public class GridPos {
    public int h;
    public int w;
    public int x;
    public int y;

    public GridPos() {
    }

    public GridPos(int h, int w, int x, int y) {
        this.h = h;
        this.w = w;
        this.x = x;
        this.y = y;
    }
}
