package org.zstack.allocator.domain.header;

public enum AllocatorDomainErrors {
    GENERAL_ERROR(1000),

    // 2XXX: DOMAIN_RELATED_ERROR
    DOMAIN_RELATED_ERROR(2000),
    DOMAIN_NOT_FOUND(2001),
    DOMAIN_IN_USE(2002),
    GLOBAL_CONFIG_UPDATE_NOT_ALLOWED(2003),

    // 3XXX: RULE_RELATED_ERROR
    RULE_RELATED_ERROR(3000),
    INVALID_RULE(3001),
    CONFLICTING_INCLUDE_EXCLUDE(3002),
    DUPLICATE_RULE(3003),
    INVALID_RULE_EFFECT(3004),

    INVALID_HOST_RULE(3100),
    HOST_NOT_IN_ZONE(3101),
    HOST_QUALIFIER_NOT_ALLOWED(3102),
    HOST_NOT_FOUND(3103),

    INVALID_CLUSTER_RULE(3200),
    CLUSTER_NOT_IN_ZONE(3201),
    CLUSTER_QUALIFIER_NOT_ALLOWED(3202),
    CLUSTER_NOT_FOUND(3203),

    INVALID_PRIMARY_STORAGE_RULE(3300),
    PRIMARY_STORAGE_NOT_IN_ZONE(3301),
    PRIMARY_STORAGE_INVALID_QUALIFIER(3302),
    PRIMARY_STORAGE_NOT_FOUND(3303),

    INVALID_L3_RULE(3400),
    L3_NOT_IN_ZONE(3401),
    L3_QUALIFIER_NOT_ALLOWED(3402),
    L3_NOT_FOUND(3403),

    INVALID_BACKUP_STORAGE_RULE(3500),
    BACKUP_STORAGE_NOT_IN_ZONE(3501),
    BACKUP_STORAGE_QUALIFIER_NOT_ALLOWED(3502),
    BACKUP_STORAGE_NOT_FOUND(3503),

    // 4XXX: ALLOCATION_RELATED_ERROR
    ALLOCATION_RELATED_ERROR(4000),
    RESOURCE_OUT_OF_DOMAIN(4001),
    DOMAIN_UUID_CHANGE_NOT_ALLOWED(4002),
    ;

    private final String code;

    AllocatorDomainErrors(int id) {
        code = String.format("ALLOCATOR.DOMAIN.%s", id);
    }

    public boolean isEqual(Object t) {
        return t.toString().equals(this.toString());
    }

    @Override
    public String toString() {
        return code;
    }
}
